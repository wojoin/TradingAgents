// **text** is bold; !!text!! is bold and red (the exact indicators and conditions of a rule).
function parts(text: string): { t: string; b: boolean; r: boolean }[] {
  return text.split(/(\*\*.+?\*\*|!!.+?!!)/).filter((t) => t).map((t) =>
    t.startsWith('**') && t.endsWith('**') && t.length > 4 ? { t: t.slice(2, -2), b: true, r: false }
      : t.startsWith('!!') && t.endsWith('!!') && t.length > 4 ? { t: t.slice(2, -2), b: true, r: true }
        : { t, b: false, r: false })
}
